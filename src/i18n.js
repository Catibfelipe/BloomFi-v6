export const DICTS = { pt, en };

export function makeT(lang) {
  const d = DICTS[lang] || pt;
  return (key, vars = {}) => {
    const v = d[key] ?? pt[key] ?? key;
    if (typeof v === 'function') return v(vars);
    return v.replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? `{${k}}`));
  };
}
